#!/usr/bin/env python3
"""Generates src/renderer/soldier_looks.rs from the pixel-art definitions in sprites4.py / items4.py. Run from this directory."""
import sys, re
sys.path.insert(0, '.')
import items4
from sprites4 import build, W, H
OUT = '#15131a'
looks = ['rifleman', 'commando', 'trooper', 'ranger', 'sapper']
names = ['RIFLEMAN', 'COMMANDO', 'TROOPER', 'RANGER', 'SAPPER']
POSES = ['idle'] + ['walk%d' % i for i in range(8)] + ['jump']
MAGIC = ('#ff00ff', '#a000a0', '#ff80ff')
BOOT_M = ('#ff0001', '#ff0002')   # magic boot colours, recoloured at runtime (default dark, or the shop boot colour)
pal = ['']
def idx(c):
    if c not in pal: pal.append(c)
    return pal.index(c)
idx(OUT)
def flat(g): return [0 if c is None else idx(c) for row in g for c in row]
# variants: 0 intact head + baked gun, 1 intact head no gun, 2 bare head + baked gun, 3 bare head no gun
DATA = []
for v in looks:
    per = []
    for bare in (False, True):
        for gun in (True, False):
            per.append([flat(build(v, 'x', p, gun, hat=255 if bare else 0, boot=BOOT_M)) for p in POSES])
    # reorder to [intact+gun, intact-nogun, bare+gun, bare-nogun]
    DATA.append(per)
def layer(draw):
    g = [[None] * W for _ in range(H)]
    def px(x, y, c):
        if 0 <= x < W and 0 <= y < H: g[y][x] = c
    def rect(x, y, w, h, c):
        for j in range(h):
            for i in range(w): px(x + i, y + j, c)
    draw(px, rect)
    filled = [[g[y][x] is not None for x in range(W)] for y in range(H)]
    for y in range(H):
        for x in range(W):
            if not filled[y][x]:
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    nx, ny = x + dx, y + dy
                    if 0 <= nx < W and 0 <= ny < H and filled[ny][nx]: g[y][x] = OUT; break
    return g
cat = open('../../src/game/store.rs').read()
hat_ids = [int(i) for i in re.findall(r'\("hat",\s*(\d+),', cat)] + [37, 38, 39, 40, 41, 42, 43]   # 37 Ben-only, 38-43 warbond/premium (not in the scrap catalog)
gun_ids = [int(i) for i in re.findall(r'\("gun_style",\s*(\d+),', cat)]
items4.NO_BLADES[0] = True
HATS = {h: flat(layer(lambda px, rect, h=h: items4.draw_hat(px, rect, h))) for h in hat_ids}
GUNS = {}; TIPS = {}
for gid in gun_ids:
    g = layer(lambda px, rect, gid=gid: items4.draw_gun(px, rect, gid, 0, MAGIC[0], MAGIC[1]))
    # tip = right-most non-outline pixel (prefer the row nearest the barrel line y=16)
    best = (-1, 16)
    for y in range(H):
        for x in range(W):
            if g[y][x] not in (None, OUT) and (x > best[0] or (x == best[0] and abs(y - 16) < abs(best[1] - 16))): best = (x, y)
    GUNS[gid] = flat(g); TIPS[gid] = best
def rgb(c): return tuple(int(c[i:i+2], 16) for i in (1, 3, 5))
o = "//! GENERATED by tools/soldier_art/gen_soldier_looks.py - do not edit. 24x32 pixel-art soldier looks (facing right).\n"
o += "//! DATA[look][variant][pose][y*W+x]; variants: 0 head+gun, 1 head no gun, 2 bare head+gun, 3 bare head no gun. Poses: idle, walk0..7, jump.\n"
o += "pub const W: usize = %d;\npub const H: usize = %d;\npub const PIV_X: f32 = 12.0;\npub const PIV_Y: f32 = 20.0;\n" % (W, H)
o += "pub const N_LOOKS: usize = 5;\npub const N_POSES: usize = 10;\n"
o += "pub const NAMES: [&str; 5] = [%s];\n" % ",".join('"%s"' % n for n in names)
o += "/// Vertical offset (px) of the body per pose, applied to hat and gun layers.\npub const POSE_BOB: [i32; 10] = [0, 0, 0, -1, -1, 0, 0, -1, -1, -1];\n"
o += "/// Extra gun-layer lift in the jump pose.\npub const JUMP_GUN_UP: i32 = -1;\n"
o += "pub const PAL: [(u8, u8, u8); %d] = [(0,0,0),%s];\n" % (len(pal), ",".join("(%d,%d,%d)" % rgb(c) for c in pal[1:]))
o += "pub const OUT_IDX: u8 = %d;\npub const TEAM_MID: u8 = %d;\npub const TEAM_DARK: u8 = %d;\npub const TEAM_LIGHT: u8 = %d;\n" % (pal.index(OUT), pal.index(MAGIC[0]), pal.index(MAGIC[1]), pal.index(MAGIC[2]))
o += "pub const BOOT_IDX: u8 = %d;\npub const BOOT_L_IDX: u8 = %d;\n" % (pal.index(BOOT_M[0]), pal.index(BOOT_M[1]))
o += "/// Shop boot colours (id 1..5): (main, highlight).\npub const BOOT_COLORS: [((u8,u8,u8),(u8,u8,u8)); 6] = [((0,0,0),(0,0,0)),%s];\n" % ",".join("((%d,%d,%d),(%d,%d,%d))" % (rgb(a) + rgb(b)) for a, b in
    [('#c83a3a', '#ff7a7a'), ('#e8e8ee', '#ffffff'), ('#e0b43a', '#ffe38a'), ('#3f5a2a', '#6a8a4a'), ('#2a7ae8', '#7ab0ff')])
nh = max(hat_ids) + 1; ng = max(gun_ids) + 1
o += "pub const N_HATS: usize = %d;\npub const N_GUNS: usize = %d;\n" % (nh, ng)
def arr(name, ty, n, items, zero):
    r = "pub static %s: [%s; %d] = [\n" % (name, ty, n)
    for i in range(n): r += "  [" + ",".join(map(str, items.get(i, zero))) + "],\n"
    return r + "];\n"
o += "/// Hat layers by shop id (0 and unused ids empty). Palette indices; OUT_IDX pixels only draw over transparent body pixels.\n"
o += arr('HATS', '[u8; W*H]', nh, HATS, [0] * (W * H))
o += "/// Gun layers by shop id (idle pose, lift 0).\n" + arr('GUNS', '[u8; W*H]', ng, GUNS, [0] * (W * H))
o += "/// Muzzle tip (x, y) in sprite pixels per gun id.\npub const GUN_TIPS: [(u8, u8); %d] = [%s];\n" % (ng, ",".join("(%d,%d)" % TIPS.get(i, (23, 16)) for i in range(ng)))
o += "pub static DATA: [[[[u8; W*H]; N_POSES]; 4]; N_LOOKS] = [\n"
for per in DATA:
    o += " [\n"
    for var in (0, 1, 2, 3):
        o += "  [\n" + "".join("   [" + ",".join(map(str, p)) + "],\n" for p in per[var]) + "  ],\n"
    o += " ],\n"
o += "];\n"
open('../../src/renderer/soldier_looks.rs', 'w').write(o)
print('palette', len(pal), 'bytes', len(o))
