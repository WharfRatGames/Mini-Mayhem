#!/usr/bin/env python3
"""Generate src/physics/wa_weapons.rs from WA's static weapon table (worms_decomp/findings/weapon_table.csv).
Columns are record offsets; object offset = record offset + 0x28c (verified on the sheep walker).
Usage: tools/gen_weapon_table.py /home/dusty/worms_decomp/findings/weapon_table.csv > src/physics/wa_weapons.rs"""
import csv, sys
rows = list(csv.reader(open(sys.argv[1])))
h = rows[0]
def g(row, k):
    if k not in h: return None
    v = row[h.index(k)]
    return int(v) if v != '' else None
out = ['//! WA weapon records (static defaults of the 71-record table, FUN_00537320/00539100). GENERATED by tools/gen_weapon_table.py -',
       '//! do not edit. `None` = the record leaves the field at 0/unset. Object offsets = record offset + 0x28c.', '',
       '#[derive(Debug, Clone, Copy, PartialEq, Eq)]', 'pub struct WaWeapon {',
       '    pub rec: u8,', '    /// +0x30 fire class (1 projectile, 2 thrown/placed, 3 special, 4 utility).', '    pub class: i32,',
       '    /// +0x34 subtype.', '    pub subtype: i32,', '    /// +0x54 blast damage, +0x60 blast radius (px).', '    pub damage: i32, pub radius: i32,',
       '    /// +0x7c wind %, +0x84 gravity %.', '    pub wind_pct: i32, pub gravity_pct: i32,',
       '    /// +0x88 default fuse ms (player-set weapons), +0x8c fixed fuse ms.', '    pub default_fuse_ms: i32, pub fuse_ms: i32,',
       '    /// +0xa4 object category (2/5 bounce+fuse, 3 sheep walker, 4 special) -> obj+0x330.', '    pub category: i32,',
       '    /// +0xac vertical bounce % (0 = taken from the launch struct), +0xb0 floor-slide %, +0xb4 bounce sound id.',
       '    pub bounce_pct: i32, pub slide_pct: i32, pub bounce_sound: i32,', '}', '',
       'pub const WEAPONS: &[WaWeapon] = &[']
n = 0
for row in rows[1:]:
    if g(row, '+0xa4') is None: continue
    z = lambda k: g(row, k) or 0
    out.append('    WaWeapon { rec: %d, class: %d, subtype: %d, damage: %d, radius: %d, wind_pct: %d, gravity_pct: %d, default_fuse_ms: %d, fuse_ms: %d, category: %d, bounce_pct: %d, slide_pct: %d, bounce_sound: %d },' % (
        int(row[0]), z('+0x30'), z('+0x34'), z('+0x54'), z('+0x60'), z('+0x7c'), z('+0x84'), z('+0x88'), z('+0x8c'), z('+0xa4'), z('+0xac'), z('+0xb0'), z('+0xb4')))
    n += 1
out += ['];', '', 'pub fn record(rec: u8) -> Option<&\'static WaWeapon> { WEAPONS.iter().find(|w| w.rec == rec) }', '',
        '#[cfg(test)]', 'mod tests {', '    use super::*;', '    #[test]', '    fn spot_checks_against_the_static_table() {',
        '        let b = record(1).unwrap();', '        assert_eq!((b.damage, b.radius, b.wind_pct, b.fuse_ms, b.category), (50, 48, 100, 9000, 2));',
        '        let g = record(6).unwrap();', '        assert_eq!((g.damage, g.radius, g.wind_pct, g.default_fuse_ms, g.fuse_ms), (50, 50, 0, 5000, 0));',
        '        let s = record(23).unwrap();', '        assert_eq!((s.damage, s.radius, s.fuse_ms, s.category), (75, 153, 20000, 3));', '    }', '}']
print('\n'.join(out))
sys.stderr.write('%d records\n' % n)
